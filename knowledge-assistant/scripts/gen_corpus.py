def render(doc: dict) -> str:
    lines = [f"# {doc['title']}", ""]
    for heading, clauses in doc["sections"]:
        lines.append(f"## {heading}")
        lines.append("")
        for clause in clauses:
            lines.append(clause)
            lines.append("")
    return "\n".join(lines)


def main() -> None:
    DOC_DIR.mkdir(parents=True, exist_ok=True)
    for doc in DOCS:
        (DOC_DIR / doc["file"]).write_text(render(doc), encoding="utf-8")

    rows = []
    for i, q in enumerate(QUESTIONS, 1):
        rows.append(
            json.dumps(
                {
                    "id": f"c{i}",
                    "question": q["question"],
                    "sources": q["sources"],
                    "must_include": q["must_include"],
                    "must_not_include": q.get("must_not_include", []),
                    "expected": q["expected"],
                    "should_answer": q.get("should_answer", True),
                },
                ensure_ascii=False,
            )
        )
    EVAL_FILE.parent.mkdir(parents=True, exist_ok=True)
    EVAL_FILE.write_text("\n".join(rows) + "\n", encoding="utf-8")

    chars = sum(len(render(d)) for d in DOCS)
    print(f"生成文档 {len(DOCS)} 份 → {DOC_DIR}")
    print(f"生成题目 {len(QUESTIONS)} 条 → {EVAL_FILE}")
    print(f"语料总字数约 {chars} 字，平均每篇 {chars // len(DOCS)} 字")


if __name__ == "__main__":
    main()
